// Builds the self-hosted world map used by the "Around the World" section
// on /profile/. Run once (or after changing an override below):
//
//   cd scripts && npm i --no-save d3-geo topojson-client world-atlas@2.0.2 i18n-iso-countries
//   node build_world_map.mjs
//
// Writes:
//   assets/img/world-map.svg  - country outlines (Natural Earth 1:110m), one
//                               <path data-c="XX"> per country, Antarctica removed
//   _data/geo.yml             - ISO alpha-2 code -> display name and pin anchor
//                               (x, y in the SVG's coordinate space)
//
// To pin a new country on the profile, tag the item in _data/profile.yml with
// `geo: XX` (ISO 3166-1 alpha-2; quote "NO" for Norway) or `geo: [XX, YY]`;
// `geo: WW` lists an online or worldwide program without a pin. Every
// country is already in geo.yml.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoNaturalEarth1, geoPath, geoArea, geoCentroid } from 'd3-geo';
import { feature } from 'topojson-client';
import countries from 'i18n-iso-countries';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
countries.registerLocale(require('i18n-iso-countries/langs/en.json'));

const W = 960, PAD = 8;
const world = JSON.parse(readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8'));
const land = feature(world, world.objects.countries).features.filter(f => f.id !== '010');

const projection = geoNaturalEarth1().fitWidth(W - PAD * 2, { type: 'FeatureCollection', features: land });
let path = geoPath(projection);
const [[x0, y0], [, y1]] = path.bounds({ type: 'FeatureCollection', features: land });
const [tx, ty] = projection.translate();
projection.translate([tx + PAD - x0, ty + PAD - y0]);
path = geoPath(projection).digits(1);
const H = Math.ceil(y1 - y0 + PAD * 2);

// Pin anchors that read better than the computed centroid (lon, lat).
const OVERRIDE = {
  US: [-98.5, 39.5], CA: [-101, 56], MY: [101.9, 3.9], FR: [2.4, 46.2], GB: [-3.2, 54.8],
  ID: [114, -1.5], NO: [9, 61], RU: [95, 61], CL: [-71, -33], NZ: [174.5, -41],
  // Too small for the 1:110m outlines; pinned without a shape.
  BH: [50.55, 26.07], SG: [103.82, 1.35], MT: [14.4, 35.9], HK: [114.17, 22.32],
  LU: [6.13, 49.61], MU: [57.55, -20.25], MV: [73.5, 4.2], QA: [51.2, 25.3],
};
const NAME = { US: 'United States', GB: 'United Kingdom', RU: 'Russia', KR: 'South Korea', KP: 'North Korea',
  IR: 'Iran', SY: 'Syria', VN: 'Vietnam', LA: 'Laos', BO: 'Bolivia', VE: 'Venezuela', TZ: 'Tanzania',
  MD: 'Moldova', CZ: 'Czechia', TW: 'Taiwan', CD: 'DR Congo', CG: 'Congo', BN: 'Brunei', AE: 'United Arab Emirates',
  CN: 'China', GM: 'Gambia', MK: 'North Macedonia', FK: 'Falkland Islands' };

const largest = f => {
  if (f.geometry.type !== 'MultiPolygon') return f;
  let best = null, area = -1;
  for (const coords of f.geometry.coordinates) {
    const g = { type: 'Polygon', coordinates: coords }, a = geoArea(g);
    if (a > area) { area = a; best = g; }
  }
  return best;
};

const geo = {};
const paths = [];
for (const f of land) {
  const a2 = f.id ? countries.numericToAlpha2(f.id) : null;
  const d = path(f);
  if (!d) continue;
  paths.push(`<path${a2 ? ` data-c="${a2}"` : ''} d="${d}"/>`);
  if (!a2) continue;
  const ll = OVERRIDE[a2] || geoCentroid(largest(f));
  const [x, y] = projection(ll);
  geo[a2] = { n: NAME[a2] || countries.getName(a2, 'en', { select: 'official' }) || f.properties.name, x, y };
}
for (const [a2, ll] of Object.entries(OVERRIDE)) {
  if (geo[a2]) continue;
  const [x, y] = projection(ll);
  geo[a2] = { n: NAME[a2] || countries.getName(a2, 'en'), x, y };
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" fill="#8a8f98" fill-opacity=".3" stroke="none">` +
  `<g class="pm-land">${paths.join('')}</g></svg>\n`;
writeFileSync(join(root, 'assets/img/world-map.svg'), svg);

const q = s => '"' + String(s).replace(/"/g, '\\"') + '"';
// Keys are quoted: YAML 1.1 would read a bare NO (Norway) as false.
const lines = Object.keys(geo).sort().map(k => `"${k}": { n: ${q(geo[k].n)}, x: ${geo[k].x.toFixed(1)}, y: ${geo[k].y.toFixed(1)} }`);
writeFileSync(join(root, '_data/geo.yml'),
  `# Generated by scripts/build_world_map.mjs - do not edit by hand.\n` +
  `# ISO 3166-1 alpha-2 -> display name (n) and pin anchor (x, y) in assets/img/world-map.svg.\n` +
  `# viewBox: 0 0 ${W} ${H}\n` + lines.join('\n') + '\n');

console.log(`world-map.svg ${(svg.length / 1024).toFixed(1)} KB, ${paths.length} shapes, viewBox ${W}x${H}; geo.yml ${lines.length} countries`);
